#!/usr/bin/env node
'use strict';

const fs = require('fs/promises');
const path = require('path');

const SOURCE_PAGE_URL = 'https://www.dmosk.ru/skachka.php?smiles=all';
const EXPECTED_COUNT = 281;
const repoRoot = path.resolve(__dirname, '..');
const assetDir = path.join(repoRoot, 'public', 'assets', 'emoji', 'qip-infium-original');
const manifestPath = path.join(repoRoot, 'public', 'js', 'qip-infium-original.js');

async function fetchBuffer(url) {
  const response = await fetch(url, {
    headers: {
      'user-agent': 'BananZa qip-infium-original importer',
    },
  });
  if (!response.ok) throw new Error(`GET ${url} failed: ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

async function fetchText(url) {
  return (await fetchBuffer(url)).toString('utf8');
}

function extractGifUrls(html) {
  const matches = [...html.matchAll(/(?:src=["']?)?((?:https?:\/\/www\.dmosk\.ru\/)?\/?img\/qip_smiles\/(\d+)\.gif)/gi)];
  const byId = new Map();
  for (const match of matches) {
    const id = Number(match[2]);
    if (!Number.isInteger(id) || id <= 0) continue;
    byId.set(id, new URL(match[1], SOURCE_PAGE_URL).href);
  }
  return [...byId.entries()]
    .sort((left, right) => left[0] - right[0])
    .map(([id, url]) => ({ id, url }));
}

function readGifDimensions(buffer, sourceLabel) {
  if (buffer.length < 10 || buffer.toString('ascii', 0, 3) !== 'GIF') {
    throw new Error(`${sourceLabel} is not a GIF image`);
  }
  return {
    width: buffer.readUInt16LE(6),
    height: buffer.readUInt16LE(8),
  };
}

function tokenForId(id) {
  return `:qip-infium-${String(id).padStart(3, '0')}:`;
}

function fileNameForId(id) {
  return `${String(id).padStart(3, '0')}.gif`;
}

function renderManifest(items) {
  const lines = [];
  lines.push('(function () {');
  lines.push("  'use strict';");
  lines.push('');
  lines.push('  // Generated by scripts/import-qip-infium-original.js.');
  lines.push(`  // Source: ${SOURCE_PAGE_URL}`);
  lines.push('  const items = Object.freeze([');
  for (const item of items) {
    lines.push(`    Object.freeze({ id: ${item.id}, token: '${item.token}', src: '${item.src}', width: ${item.width}, height: ${item.height}, label: '${item.label}' }),`);
  }
  lines.push('  ]);');
  lines.push('');
  lines.push('  window.BananzaQipInfiumOriginal = Object.freeze({');
  lines.push("    id: 'qip-infium-original',");
  lines.push("    label: 'QIP',");
  lines.push(`    source: '${SOURCE_PAGE_URL}',`);
  lines.push('    items,');
  lines.push('  });');
  lines.push('})();');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const html = await fetchText(SOURCE_PAGE_URL);
  const gifUrls = extractGifUrls(html);
  if (gifUrls.length !== EXPECTED_COUNT) {
    throw new Error(`Expected ${EXPECTED_COUNT} QIP GIFs, found ${gifUrls.length}`);
  }

  await fs.mkdir(assetDir, { recursive: true });
  const items = [];
  for (const { id, url } of gifUrls) {
    const fileName = fileNameForId(id);
    const buffer = await fetchBuffer(url);
    const dimensions = readGifDimensions(buffer, url);
    await fs.writeFile(path.join(assetDir, fileName), buffer);
    items.push({
      id,
      token: tokenForId(id),
      src: `/assets/emoji/qip-infium-original/${fileName}`,
      width: dimensions.width,
      height: dimensions.height,
      label: `QIP ${String(id).padStart(3, '0')}`,
    });
  }

  await fs.writeFile(manifestPath, renderManifest(items), 'utf8');
  console.log(`Imported ${items.length} QIP GIFs.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
