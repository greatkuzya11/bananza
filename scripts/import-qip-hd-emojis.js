const fs = require('fs/promises');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const defaultSourceDir = path.resolve(repoRoot, '..', 'qip-emoji');
const sourceDir = path.resolve(process.argv[2] || process.env.QIP_HD_SOURCE_DIR || defaultSourceDir);
const assetDir = path.join(repoRoot, 'public', 'assets', 'emoji', 'qip-hd');
const manifestPath = path.join(repoRoot, 'public', 'js', 'qip-hd.js');
const jsonManifestPath = path.join(assetDir, 'manifest.json');

function readGifDimensions(buffer) {
  if (buffer.length < 10 || buffer.toString('ascii', 0, 3) !== 'GIF') {
    throw new Error('Not a GIF file');
  }
  return {
    width: buffer.readUInt16LE(6),
    height: buffer.readUInt16LE(8),
  };
}

function slugFromFileName(fileName) {
  const base = path.basename(fileName, path.extname(fileName)).toLowerCase();
  return base
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-{2,}/g, '-');
}

function tokenForFileName(fileName) {
  const slug = slugFromFileName(fileName);
  if (!slug) throw new Error(`Cannot create token for ${fileName}`);
  return `:qip-hd-${slug}:`;
}

function jsString(value) {
  return JSON.stringify(String(value));
}

function renderBrowserManifest(items) {
  const lines = [];
  lines.push('(function () {');
  lines.push("  'use strict';");
  lines.push('');
  lines.push('  // Generated by scripts/import-qip-hd-emojis.js.');
  lines.push(`  // Source: ${sourceDir.replace(/\\/g, '/')}`);
  lines.push('  const items = Object.freeze([');
  items.forEach((item) => {
    lines.push(`    Object.freeze({ id: ${item.id}, token: ${jsString(item.token)}, src: ${jsString(item.src)}, width: ${item.width}, height: ${item.height}, label: ${jsString(item.label)} }),`);
  });
  lines.push('  ]);');
  lines.push('');
  lines.push('  window.BananzaQipHdEmojis = Object.freeze({');
  lines.push("    id: 'qip-hd',");
  lines.push("    label: 'QIP HD',");
  lines.push(`    source: ${jsString(sourceDir)},`);
  lines.push('    items,');
  lines.push('  });');
  lines.push('})();');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const sourceEntries = await fs.readdir(sourceDir, { withFileTypes: true });
  const gifFiles = sourceEntries
    .filter((entry) => entry.isFile() && /\.gif$/i.test(entry.name))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, 'en'));
  if (!gifFiles.length) throw new Error(`No GIF files found in ${sourceDir}`);

  await fs.rm(assetDir, { recursive: true, force: true });
  await fs.mkdir(assetDir, { recursive: true });

  const seenTokens = new Set();
  const items = [];
  for (const [index, fileName] of gifFiles.entries()) {
    const token = tokenForFileName(fileName);
    if (seenTokens.has(token)) throw new Error(`Duplicate QIP HD token: ${token}`);
    seenTokens.add(token);

    const sourcePath = path.join(sourceDir, fileName);
    const buffer = await fs.readFile(sourcePath);
    const dimensions = readGifDimensions(buffer);
    const targetPath = path.join(assetDir, fileName);
    await fs.writeFile(targetPath, buffer);

    items.push({
      id: index + 1,
      token,
      src: `/assets/emoji/qip-hd/${fileName}`,
      width: dimensions.width,
      height: dimensions.height,
      label: `QIP HD ${path.basename(fileName, path.extname(fileName)).replace(/[_-]+/g, ' ')}`,
      fileName,
    });
  }

  await fs.writeFile(manifestPath, renderBrowserManifest(items), 'utf8');
  await fs.writeFile(jsonManifestPath, `${JSON.stringify({
    id: 'qip-hd',
    label: 'QIP HD',
    source: sourceDir,
    items,
  }, null, 2)}\n`, 'utf8');
  console.log(`Imported ${items.length} QIP HD GIFs from ${sourceDir}.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
